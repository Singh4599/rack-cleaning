// Staff: only Pratap and Anil
export const STAFF = ['Pratap', 'Anil'];
export const UNITS = ['Unit 11', 'Unit 12'];

const METHODS_WEIGHTED = ['Dry Wipe', 'Dry Wipe', 'Wet Wipe', 'Wet Wipe', 'Sweep & Wipe', 'Sanitize & Wipe', 'Vacuum & Wipe'];

const REMARKS_OK = [
  'OK – No issues found',
  'Cleaned thoroughly',
  'Minor dust removed',
  'Routine clean done',
  'OK – Regular cleaning',
  'Rack cleared and wiped',
  'OK – Checked & cleaned',
  'Clean – no spillage',
  'Surface wiped, no issues',
  'OK – Compliant',
];
const REMARKS_ISSUE = [
  'Minor spill found and cleaned',
  'Dust accumulation – cleared',
  'Old stock residue removed',
  'Light staining found – cleaned',
  'Spillage near base – cleaned',
];

// Time slots: one per rack per day
// Slot A: 09:00–10:00, Slot B: 12:30–13:00, Slot C: 17:30–18:00
const TIME_SLOTS = [
  { label: 'Morning', hMin: 9,  hMax: 10, mMinFirst: 0,  mMaxLast: 0 },
  { label: 'Midday',  hMin: 12, hMax: 13, mMinFirst: 30, mMaxLast: 0 },
  { label: 'Evening', hMin: 17, hMax: 18, mMinFirst: 30, mMaxLast: 0 },
];

// ── GENERATE ENTRIES FOR ONE DAY ───────────────────────────────────────────────
// 3–5 entries per day per unit (sometimes 6). Sunday = 0 entries.
// unit param: 'Unit 11' or 'Unit 12'
export function generateDayEntries(dateStr, unit) {
  const d = new Date(dateStr + 'T00:00:00');
  // Sunday (0) → no entries
  if (d.getDay() === 0) return [];

  const unitStr  = unit || 'Unit 11';
  // Unique seed per date+unit so both units get different but deterministic data
  const unitSeed = unitStr === 'Unit 12' ? 99991 : 0;
  const dateEpoch = d.getTime() / 1000;
  const rng = seeded(dateEpoch + unitSeed);

  const racks = ['Rack 1', 'Rack 2', 'Rack 3'];

  // Base 3 entries: one per rack, each in different time slot
  const slotOrder = shuffle(rng, [0, 1, 2]);

  const entries = racks.map((rack, ri) => {
    const slot  = TIME_SLOTS[slotOrder[ri]];
    const rng2  = seeded(dateEpoch + unitSeed + ri * 31337 + 1);
    const time  = pickTimeInSlot(rng2, slot);
    const staffName = pick(rng2, STAFF);
    const method    = pick(rng2, METHODS_WEIGHTED);
    const useIssue  = rng2() < 0.08;
    const remark    = useIssue ? pick(rng2, REMARKS_ISSUE) : pick(rng2, REMARKS_OK);
    return {
      date:          dateStr,
      rackId:        rack,
      unit:          unitStr,
      area:          '',
      cleaningTime:  time,
      cleaningDone:  true,
      method,
      checkedBy:     staffName,
      remarks:       remark,
      autoGenerated: true,
      slot:          slot.label,
    };
  });

  // Randomly add 0–2 extra entries (different rack+slot combo) to reach 3-5 or 6
  const extraCount = (() => {
    const r = rng();
    if (r < 0.25) return 0;   // 25% → 3 entries
    if (r < 0.65) return 1;   // 40% → 4 entries
    if (r < 0.90) return 2;   // 25% → 5 entries
    return 3;                  // 10% → 6 entries
  })();

  // Extra slots use "bonus" times within existing slot windows, different rack pick
  const bonusSlots = shuffle(rng, [0, 1, 2]).slice(0, Math.min(extraCount, 3));
  bonusSlots.forEach((si, ei) => {
    const slot  = TIME_SLOTS[si];
    const rng3  = seeded(dateEpoch + unitSeed + ei * 77777 + 9999);
    const rack  = pick(rng3, racks); // may repeat rack — different time is fine
    const time  = pickTimeInSlot(rng3, slot);
    const staffName = pick(rng3, STAFF);
    const method    = pick(rng3, METHODS_WEIGHTED);
    const remark    = pick(rng3, REMARKS_OK);
    entries.push({
      date:          dateStr,
      rackId:        rack,
      unit:          unitStr,
      area:          '',
      cleaningTime:  time,
      cleaningDone:  true,
      method,
      checkedBy:     staffName,
      remarks:       remark,
      autoGenerated: true,
      slot:          slot.label,
    });
  });

  // Sort by time ascending
  entries.sort((a, b) => a.cleaningTime.localeCompare(b.cleaningTime));
  return entries;
}

// ── GENERATE RANGE ─────────────────────────────────────────────────────────────
export function generateDateRange(fromStr, toStr, unit) {
  const all = [];
  const from = new Date(fromStr + 'T00:00:00');
  const to   = new Date(toStr   + 'T00:00:00');
  const cur  = new Date(from);
  while (cur <= to) {
    const ds = `${cur.getFullYear()}-${pad(cur.getMonth() + 1)}-${pad(cur.getDate())}`;
    all.push(...generateDayEntries(ds, unit));
    cur.setDate(cur.getDate() + 1);
  }
  return all;
}

export function todayStr() {
  const d = new Date();
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}
